/**
 * Generates supabase/migration.sql from the bundled seed dataset.
 *
 * Creates one `pmos_*` table per baseline collection (team members, objectives,
 * meetings, …) holding the entity as a JSONB row, enables RLS with an anon
 * SELECT policy, and upserts the current real data. LGP campaigns are NOT
 * migrated — they stay live from the existing `projects` / `performance_data`
 * tables. Run once in the Supabase SQL editor; safe to re-run (idempotent).
 *
 *   node scripts/gen-supabase-migration.mjs
 */
import { build } from 'esbuild';
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Bundle + evaluate the TS seed module (type-only imports are erased by esbuild).
const result = await build({
  entryPoints: [resolve(root, 'src/data/seedData.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  write: false,
  loader: { '.json': 'json' },
});
const code = result.outputFiles[0].text;
const mod = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
const seed = mod.seedData;

/** [seed key, table name] — lgpCampaigns is intentionally excluded (live). */
const COLLECTIONS = [
  ['teamMembers', 'pmos_team_members'],
  ['objectives', 'pmos_objectives'],
  ['actionItems', 'pmos_action_items'],
  ['meetings', 'pmos_meetings'],
  ['performance', 'pmos_performance'],
  ['assessments', 'pmos_assessments'],
  ['readiness', 'pmos_readiness'],
  ['projects', 'pmos_projects'],
];

const q = (obj) => `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`;
const qt = (s) => `'${String(s).replace(/'/g, "''")}'`;

function tableDDL(table) {
  return `create table if not exists public.${table} (
  id text primary key,
  ord integer not null default 0,
  data jsonb not null,
  updated_at timestamptz not null default now()
);
alter table public.${table} enable row level security;
drop policy if exists "anon_read_${table}" on public.${table};
create policy "anon_read_${table}" on public.${table} for select to anon using (true);`;
}

const out = [];
out.push('-- PMOS baseline → Supabase. Generated by scripts/gen-supabase-migration.mjs');
out.push('-- Paste into the Supabase SQL editor and Run. Idempotent (safe to re-run).');
out.push('-- LGP campaigns stay live from the existing projects/performance_data tables.');
out.push('');
out.push('begin;');
out.push('');

const summary = [];
for (const [key, table] of COLLECTIONS) {
  const rows = Array.isArray(seed[key]) ? seed[key] : [];
  out.push(`-- ${table} (${rows.length} rows)`);
  out.push(tableDDL(table));
  if (rows.length) {
    const prefix = table.replace(/^pmos_/, '');
    const values = rows
      .map((item, i) => `  (${qt(item.id ?? `${prefix}-${i}`)}, ${i}, ${q(item)})`)
      .join(',\n');
    out.push(`insert into public.${table} (id, ord, data) values`);
    out.push(values + '\non conflict (id) do update set data = excluded.data, ord = excluded.ord, updated_at = now();');
  }
  out.push('');
  summary.push(`${table}: ${rows.length}`);
}

// program is a singleton object, not an array.
out.push('-- pmos_program (singleton)');
out.push(`create table if not exists public.pmos_program (
  id text primary key,
  data jsonb not null,
  updated_at timestamptz not null default now()
);
alter table public.pmos_program enable row level security;
drop policy if exists "anon_read_pmos_program" on public.pmos_program;
create policy "anon_read_pmos_program" on public.pmos_program for select to anon using (true);`);
out.push(`insert into public.pmos_program (id, data) values ('program', ${q(seed.program ?? {})})`);
out.push('on conflict (id) do update set data = excluded.data, updated_at = now();');
out.push('');
summary.push('pmos_program: 1');

out.push('commit;');
out.push('');

mkdirSync(resolve(root, 'supabase'), { recursive: true });
const outPath = resolve(root, 'supabase/migration.sql');
writeFileSync(outPath, out.join('\n'));
console.log('Wrote', outPath);
console.log(summary.join('  |  '));
